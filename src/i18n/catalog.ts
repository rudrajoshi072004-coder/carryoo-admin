export type AdminCatalog = typeof en;

const CATALOG: Record<AdminLocale, AdminCatalog> = { en, hi, mr, gu };

function readPath(tree: unknown, key: string): string | undefined {
  if (typeof tree === "object" && tree && key in tree) {
    const direct = (tree as Record<string, unknown>)[key];
    if (typeof direct === "string") return direct;
  }
  let node: unknown = tree;
  for (const part of key.split(".")) {
    if (node == null || typeof node !== "object" || !(part in (node as object))) return undefined;
    node = (node as Record<string, unknown>)[part];
  }
  return typeof node === "string" ? node : undefined;
}

export function adminLabel(locale: AdminLocale, key: string): string {
  return readPath(CATALOG[locale], key) ?? readPath(CATALOG.en, key) ?? key;
}

